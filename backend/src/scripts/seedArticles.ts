async function seedArticles(): Promise<void> {
  try {
    console.log('Connecting to database...');
    await connectDB();

    console.log('Starting article seeding...');

    // Get all categories
    const categories = await Category.find({ isActive: true }).lean();
    if (categories.length === 0) {
      console.log('No categories found. Please run seed:categories first.');
      await disconnectDB();
      process.exit(1);
    }

    // Get or create an admin user to use as author
    let adminUser = await User.findOne({ role: UserRole.ADMIN }).lean();
    if (!adminUser) {
      console.log('No admin user found. Creating a temporary admin user for articles...');
      adminUser = await User.create({
        name: 'Admin',
        email: 'admin@majalpost.com',
        password: 'TempPass123',
        role: UserRole.ADMIN,
      });
    }

    let totalCreated = 0;

    // Create articles for each category
    for (const category of categories) {
      const articles = articlesByCategory[category.slug];
      
      if (!articles || articles.length === 0) {
        console.log(`⚠ No articles defined for category: ${category.name} (${category.slug})`);
        continue;
      }

      console.log(`\nCreating articles for category: ${category.name} (${category.slug})`);

      for (const articleData of articles) {
        const slug = generateSlug(articleData.title);

        // Check if article already exists
        const existingArticle = await Article.findOne({ slug });
        if (existingArticle) {
          console.log(`  ⏭ Skipping existing article: ${articleData.title}`);
          continue;
        }

        // Create the article
        const article = await Article.create({
          title: articleData.title,
          excerpt: articleData.excerpt,
          content: articleData.content.trim(),
          slug,
          category: category._id,
          author: adminUser._id,
          status: ArticleStatus.PUBLISHED,
          isPublished: true,
          publishedAt: new Date(),
        });

        console.log(`  ✓ Created: ${articleData.title}`);
        totalCreated++;
      }
    }

    console.log(`\n✅ Article seeding completed successfully!`);
    console.log(`Total articles created: ${totalCreated}`);
  } catch (error) {
    console.error('❌ Error seeding articles:', error);
    throw error;
  } finally {
    await disconnectDB();
    console.log('Database connection closed');
  }
}

// Run the seed script
seedArticles()
  .then(() => {
    console.log('Script finished');
    process.exit(0);
  })
  .catch((error) => {
    console.error('Script failed:', error);
    process.exit(1);
  });

